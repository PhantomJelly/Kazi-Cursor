class KaziL10nScope extends InheritedWidget {
  const KaziL10nScope({
    super.key,
    required this.language,
    required super.child,
  });

  final AppLanguage language;

  @override
  bool updateShouldNotify(KaziL10nScope oldWidget) =>
      language != oldWidget.language;
}

String t(BuildContext context, String key, [Map<String, String>? vars]) {
  final scope = context.dependOnInheritedWidgetOfExactType<KaziL10nScope>();
  return lookup(
    key,
    scope?.language ?? SettingsStore.instance.language,
    vars,
  );
}

String tRaw(String key, [Map<String, String>? vars]) {
  return lookup(key, SettingsStore.instance.language, vars);
}

String lookup(String key, AppLanguage language, [Map<String, String>? vars]) {
  var text = _tables[language]?[key] ?? _tables[AppLanguage.english]?[key] ?? key;
  vars?.forEach((name, value) {
    text = text.replaceAll('{$name}', value);
  });
  return text;
}

